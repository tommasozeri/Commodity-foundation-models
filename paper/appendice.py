FM = ["Timestral-28M", "Timestral-209M", "TimesFM-3", "Chronos-2"]
SIGLA = {"Timestral-28M": "T-28M", "Timestral-209M": "T-209M", "TimesFM-3": "TimesFM-3", "Chronos-2": "Chronos-2",
         "ARIMA": "ARIMA", "ETS": "ETS", "GARCH-t": "GARCH-t", "EGARCH-t": "EGARCH-t",
         "Simulazione storica": "Sim. storica" if LANG == "it" else "Hist. sim.",
         "Media 22g": "Media 22g" if LANG == "it" else "22-day mean"}


def marca(d: pd.DataFrame, val: str, pcol: str) -> pd.Series:
    """Valore con asterisco se significativo dopo Benjamini-Hochberg al 10% sugli asset (per modello)."""
    out = d[val].map(lambda x: f"{x:.3f}")
    for _, g in d.groupby("modello"):
        p = g[pcol].to_numpy(float)
        ok = np.isfinite(p)
        rej = np.zeros(len(g), bool)
        if ok.any():
            rej[ok] = P.bh_reject(p[ok])
        out.loc[g.index[rej]] = out.loc[g.index[rej]] + "$^{*}$"
    return out


def tabella(d: pd.DataFrame, modelli: list[str], caption: str, label: str) -> str:
    assets = [a for a in P.ASSETS if a in set(d["asset"])]
    t = d.pivot_table(index="asset", columns="modello", values="cella", aggfunc="first").reindex(assets)[modelli]
    righe = [" & ".join([NOME.get(a, a), *t.loc[a].fillna("").tolist()]) + r" \\" for a in assets]
    cols = "l" + "r" * len(modelli)
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering", r"\footnotesize", rf"\caption{{{caption}}}\label{{{label}}}",
        rf"\begin{{tabular}}{{{cols}}}", r"\toprule",
        " & ".join([TXT["asset"], *[SIGLA[m] for m in modelli]]) + r" \\", r"\midrule", *righe, r"\bottomrule",
        r"\end{tabular}", r"\end{table}", ""])


def main() -> None:
    out = list(TXT["head"])
    p = pd.read_csv(RIS / "prezzo.csv")
    p = p[p["modello"].isin([*FM, "ARIMA", "ETS"])].copy()
    for h in P.HORIZONS:
        d = p[p["h"] == h].copy()
        d["cella"] = marca(d, "CRPS/RW", "DM p (CRPS)")
        out.append(tabella(d, [*FM, "ARIMA", "ETS"],
                           TXT["prezzo"].replace("{h}", str(h)), f"tab:app-prezzo-{h}"))
    r = pd.read_csv(RIS / "rendimento_var.csv")
    mod_r = ["Timestral-28M", "Timestral-209M", "Chronos-2", "GARCH-t", "EGARCH-t", "Simulazione storica"]
    d = r[(r["alpha"].round(2) == 0.01) & r["modello"].isin(mod_r)].copy()
    d["cella"] = d.apply(lambda x: f"{100 * x['violazioni']:.1f}" + ("$^{\\dagger}$" if x["Kupiec p"] < 0.05 else ""),
                         axis=1)
    out.append(tabella(d, mod_r, TXT["var"], "tab:app-var"))
    d = r[(r["alpha"].round(2) == 0.10) & r["modello"].isin([*FM, "GARCH-t", "EGARCH-t"])].copy()
    d["cella"] = marca(d, "pinball/SS", "DM p (pinball)")
    out.append(tabella(d, [*FM, "GARCH-t", "EGARCH-t"],
                       TXT["pinball"], "tab:app-pinball"))
    v = pd.read_csv(RIS / "volatilita.csv")
    v = v[v["modello"].isin([*FM, "Media 22g"])].copy()
    for h in P.HORIZONS:
        d = v[v["h"] == h].copy()
        d["cella"] = marca(d, "QLIKE/HAR", "DM p (QLIKE)")
        out.append(tabella(d, [*FM, "Media 22g"], TXT["vol"].replace("{h}", str(h)), f"tab:app-vol-{h}"))
    TXT["out"].write_text("\n".join(out), encoding="utf-8")
    print("scritto", TXT["out"])


if __name__ == "__main__":
    main()
